def get_vision_response(
    image_bytes: bytes, prompt: str, model=OLLAMA_VISION_MODEL
) -> str:
    """Helper to query Ollama Vision models."""
    try:
        b64_image = base64.b64encode(image_bytes).decode("utf-8")
        response = ollama_client.chat(
            model=model,
            messages=[{"role": "user", "content": prompt, "images": [b64_image]}],
        )
        content = response.get("message", {}).get("content", "")
        return clean_think_tags(content)
    except Exception as e:
        print(f"Ollama Vision Error [{model}]: {e}")
        return f"[Error: Unable to analyze image using '{model}'.]"
