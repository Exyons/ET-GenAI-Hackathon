from typing import TypedDict, Optional, List, Dict, Any
from ollama import Client
import chromadb
import chromadb.utils.embedding_functions as embedding_functions
import os
import re
import base64
from dotenv import load_dotenv

# Load environment variables
load_dotenv()

DB_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "chroma_db")

# Environment configurations
OLLAMA_BASE_URL = os.environ.get("OLLAMA_BASE_URL", "http://localhost:11434")
OLLAMA_MODEL = os.environ.get("OLLAMA_MODEL", "llama3.1")
OLLAMA_VISION_MODEL = os.environ.get("OLLAMA_VISION_MODEL", "llama3.2-vision")

# Initialize Ollama client pointing to the specific host
ollama_client = Client(host=OLLAMA_BASE_URL)

# Setup Chroma Client
client = chromadb.PersistentClient(path=DB_DIR)
default_ef = embedding_functions.DefaultEmbeddingFunction()
try:
    collection = client.get_collection(
        name="agri_compliance", embedding_function=default_ef
    )
except Exception:
    collection = None


def clean_think_tags(text: str) -> str:
    """Removes <think>...</think> tags and their contents often generated by thinking models."""
    cleaned = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL)
    return cleaned.strip()


def translate_to_english_helper(query: str, lang: str) -> str:
    """Translates the native user query to English."""
    if lang == "en" or lang.lower() == "english" or lang.startswith("en"):
        return query

    prompt = f"Translate the following text from {lang} to English. Preserve any local agricultural terms by transliterating them. Return ONLY the English translation.\nText: {query}"
    try:
        response = ollama_client.chat(
            model=OLLAMA_MODEL, messages=[{"role": "user", "content": prompt}]
        )
        return (
            clean_think_tags(response.get("message", {}).get("content", "")).strip()
            or query
        )
    except Exception:
        return query


def check_intent_helper(query: str) -> bool:
    """Checks if the query is agricultural."""
    prompt = f"Classify this query: '{query}'. Is this query related to agriculture, farming, crops, weather, or pests? Reply with ONLY 'YES' or 'NO'."
    try:
        response = ollama_client.chat(
            model=OLLAMA_MODEL, messages=[{"role": "user", "content": prompt}]
        )
        ans = (
            clean_think_tags(response.get("message", {}).get("content", ""))
            .strip()
            .upper()
        )
        return "YES" in ans
    except Exception:
        return True  # Default to true if fails


def fetch_rag_context_helper(query: str) -> List[str]:
    """Fetches relevant compliance guidelines from Vector DB."""
    if not collection:
        return []
    try:
        results = collection.query(query_texts=[query], n_results=3)
        return results["documents"][0] if results["documents"] else []
    except Exception:
        return []


